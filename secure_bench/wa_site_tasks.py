"""List the WebArena task ids (``<site>-<N>``) for a SITE, read from the official resolved configs
(``webarena_official/config_files/{N}.json``, generated by setup/20_webarena_docker.sh).

Only SINGLE-site tasks are listed — multi-site tasks span more than one container and the per-site parallel
runner (run_parallel.py) can't schedule them. The four sites this repo stands up are reddit / shopping /
shopping_admin / gitlab; the runners resolve any id you pass (see run_secure_webarena.resolve_task).

  python secure_bench/wa_site_tasks.py reddit
  scripts/webarena_secure.sh --workers 3 --model claude-opus-4-8 \
      --tasks $(python secure_bench/wa_site_tasks.py reddit) --skip-done
"""
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import paths  # noqa: E402


def site_task_ids(site):
    """Sorted [<site>-<N>, ...] for every single-site config whose only site is `site`."""
    cfg_dir = os.path.join(paths.WEBARENA_OFFICIAL, "config_files")
    if not os.path.isdir(cfg_dir):
        sys.exit(f"no config_files at {cfg_dir} — run setup/20_webarena_docker.sh (generate_test_data) first")
    out = []
    for f in glob.glob(os.path.join(cfg_dir, "*.json")):
        try:
            d = json.load(open(f, encoding="utf-8"))
        except Exception:
            continue
        if not isinstance(d, dict):                        # skip the top-level LIST files (test.raw.json / test.json),
            continue                                       # not per-task configs -> `.get` would raise AttributeError
        if d.get("sites") == [site]:                       # single-site tasks for THIS site only
            n = os.path.splitext(os.path.basename(f))[0]
            try:
                out.append((int(n), f"{site}-{n}"))
            except ValueError:
                continue
    return [t for _, t in sorted(out)]


def _single_site_labels():
    """Diagnostic: how many single-site tasks exist per site label (to catch a wrong site name)."""
    cfg_dir = os.path.join(paths.WEBARENA_OFFICIAL, "config_files")
    counts = {}
    for f in glob.glob(os.path.join(cfg_dir, "*.json")):
        try:
            s = json.load(open(f, encoding="utf-8")).get("sites")
        except Exception:
            continue
        if isinstance(s, list) and len(s) == 1:
            counts[s[0]] = counts.get(s[0], 0) + 1
    return counts


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: wa_site_tasks.py <site>   (single-site labels present shown below)\n"
                 f"  labels: {_single_site_labels()}")
    site = sys.argv[1]
    ids = site_task_ids(site)
    if not ids:
        sys.stderr.write(f"no single-site tasks for {site!r}. single-site labels present: {_single_site_labels()}\n")
        sys.exit(2)
    print(" ".join(ids))


if __name__ == "__main__":
    main()
